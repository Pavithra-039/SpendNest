// In-browser ZIP archive generator using JSZip
import { CONVERSATION_ANALYSES } from '../data/analyses';

const routeFolderMap = {
  'Deal Next Steps': 'deal_next_steps',
  'Sales Coaching': 'sales_coaching',
  'Customer Success & Risk': 'customer_success',
  'Partnership / Channel': 'partnerships',
  'Vendor / Product Evaluation': 'vendor_evaluation',
  'Internal Operations & Training': 'internal_ops',
  'Disqualified / Unserviceable': 'disqualified',
  'Competitor Intelligence': 'deal_next_steps',
  'Administrative Follow-Up': 'customer_success',
  'Customer Follow-Up': 'deal_next_steps',
  'Nurture / Passive Follow-Up': 'deal_next_steps'
};

export async function generateExportZip(engine) {
  if (typeof window.JSZip === 'undefined') {
    throw new Error('JSZip library is not loaded');
  }

  const zip = new window.JSZip();
  const records = engine.getAllRecordsList();
  const manifestRows = [];

  // Folders
  const folders = {
    deal_next_steps: zip.folder('deal_next_steps'),
    sales_coaching: zip.folder('sales_coaching'),
    customer_success: zip.folder('customer_success'),
    partnerships: zip.folder('partnerships'),
    vendor_evaluation: zip.folder('vendor_evaluation'),
    internal_ops: zip.folder('internal_ops'),
    disqualified: zip.folder('disqualified'),
    daily_briefs: zip.folder('daily_briefs')
  };

  records.forEach(r => {
    const ref = r.record_ref;
    const isCall = r.source_type === 'call';
    const analysis = CONVERSATION_ANALYSES[ref];
    const outputPaths = [];

    if (analysis) {
      r.active_routes.forEach(route => {
        const folderName = routeFolderMap[route] || 'deal_next_steps';
        const fileName = `${ref}_${r.source_type}_${folderName}.md`;
        const relPath = `${folderName}/${fileName}`;

        const fileContent = `# SpendNest Revenue Intelligence Output
**Record Reference:** ${ref}  
**Source Type:** ${r.source_type}  
**Source ID:** ${r.source_id}  
**Applied Source Revision:** ${r.applied_revision}  
**Assigned Route:** ${route}  
**All Conversation Destinations:** ${r.active_routes.join(', ')}  
**Manual Override Active:** ${r.is_manually_overridden ? 'YES (Preserved by Manager)' : 'NO (Automated Suggestion)'}  
**Company / Account:** ${analysis.company}  
**Contact / Counterpart:** ${analysis.contact}  
**SpendNest Representative:** ${analysis.rep}  
**Timestamp:** ${isCall ? r.payload.started_at : r.payload.starts_at} (Asia/Kolkata: 21 Aug 2026)  
**Duration:** ${r.payload.duration_seconds || 'N/A'} seconds  
**Processing & Review State:** ${r.review_state}  

---

## 1. What Happened and Why It Matters
${analysis.summary}

## 2. Supporting Evidence & Source Citations
${analysis.evidence}

## 3. What the Evidence Does NOT Establish (Uncertainty & Boundaries)
${analysis.doesNotEstablish}

## 4. Actionable Next Steps & Ownership
${analysis.nextSteps}

**Direct Owner(s):** ${analysis.owners}

---
*Generated by SpendNest Revenue Intelligence Engine. Manifest verified against Source Revision ${r.applied_revision}.*
`;

        if (folders[folderName]) {
          folders[folderName].file(fileName, fileContent);
        }
        outputPaths.push(relPath);
      });
    }

    manifestRows.push({
      source_type: r.source_type,
      source_id: r.source_id,
      record_ref: ref,
      applied_revision: r.applied_revision,
      routes: r.active_routes.join('; '),
      output_paths: outputPaths.join('; ') || 'NONE (Metadata Only)',
      review_state: r.review_state,
      is_manually_overridden: r.is_manually_overridden,
      analysis_freshness: r.analysis_freshness
    });
  });

  // Daily Brief
  const briefContent = `# SpendNest Manager Daily Intelligence Brief
**Date:** 21 August 2026 | **Timezone:** Asia/Kolkata  
**Scope:** Review of all 44 Intake Records (30 Outbound/Inbound Calls, 14 Scheduled Meetings)  
**Status:** Export Generated with Applied Revisions & Preserved Overrides  

---

## Executive Summary
Across 44 total interactions on 21 August 2026, SpendNest logged 30 phone dials and 14 scheduled calendar sessions. Out of these, 18 conversations contain substantive adapted transcripts (10 calls, 8 meetings). Overall transcript coverage sits at **40.9%** (18/44), with meeting coverage at **57.1%** (8/14) and call coverage at **33.3%** (10/30). 

Key developments include one top-tier corporate channel agreement nearing closure (**Harborpath Advisory - M01**), two critical customer churn and software defect escalations (**Cedarwave Distribution - M04** and **Willowfield Trust - M07**), one active sales pipeline quote requiring CFO review (**Asterloom Systems - M03**), and one crucial strategic vendor evaluation for our Q4 electronic invoicing expansion (**LedgerBridge - M02**).

---

## 1. Top Escalations & Churn Risks (Immediate Action Required)
1. **Cedarwave Distribution (M04) — Credit vs Prepaid Churn Hazard**
   - *Issue:* Existing prepaid card programme closes in weeks. Prospect needs corporate credit cards (holding INR 1.3 crore bank facility) and questioned SpendNest's value proposition when informed our bank feed will not display real-time available limits (*M04 Turn 25-26*).
   - *Action:* Escalate to Head of CS; verify bank partner API capabilities; assist with department user restructuring.
2. **Willowfield Trust (M07) — Production Bug Cluster & Payment Release Lock**
   - *Issue:* Live customer demonstrated 4 software bugs: description edits reverting (*Turn 3-7*), document upload failing on recreate payment (*Turn 13-15*), bulk reimbursements locked in "Processing" state (*Turn 19*), and "Mark as paid" retaining previous item values (*Turn 22-25*).
   - *Action:* Confirm reimbursement batch release within 2 hours; log P1 engineering tickets for description cache and form resets.
3. **Brookmint Holdings / Northkite (M09) — Onboarding Login Lockout**
   - *Issue:* Brookmint onboarding blocked due to "token has expired" error on fresh password reset emails (*Turn 21*). Separation of duties conflict identified with AP officer accessing shared accounts mailbox (*Turn 11-17*).
   - *Action:* Engineering auth fix for token TTL; guide client to configure individual role-based admin credentials.

---

## 2. Deal Follow-up & Commercial Pipeline Priorities
1. **Asterloom Systems (M03) — Written CFO Proposal & Setup Fee Clarification**
   - *Issue:* Demo for 65-employee firm (~INR 10-13 lakh monthly spend). Pilot planned for 4-5 employees. Pricing friction occurred when rep quoted INR 39,000 without upfront separation of INR 26k subscription vs INR 13k integration setup (*Turn 23-24*).
   - *Action:* Send itemized proposal separating recurring and one-time fees; provide 1-page business case for CFO review.
2. **Harborpath Advisory (M01) — Partnership MOU & Unique Link Provisioning**
   - *Opportunity:* Advisory firm agrees to refer newly incorporated US entities for USD 260 bounty + spend bonuses (*Turn 9*). Partner requested automated unique tracking link (*Turn 21*) and proposed marketing podcast (*Turn 26*).
   - *Action:* Send partner MOU, generate custom referral link, introduce marketing team.
3. **Willowbank Advisory (C07) — Channel Partnership Discovery**
   - *Opportunity:* Domestic & overseas formation advisory firm confirms routine referrals for virtual business accounts (*C07 exact quote*).
   - *Action:* Send partnership overview via messaging app; execute Monday morning follow-up call.
4. **Milan Developer API (C03) & Mapletrail Services (M06)**
   - *Action:* Kiran to send proposal email on developer API and event notifications; Dev to send receivables automation & SOC2 compliance info to Mapletrail branch finance lead.

---

## 3. Practical Sales Coaching Priorities
1. **Upfront Pricing Transparency (M03 - Asterloom):** Coach reps to state one-time integration fees separately from annual subscriptions at the start of commercial discussions. Springing a 50% price increase during a closing call damages buyer trust.
2. **Cold Outreach Ethics & Boundary Respect (C09 & C10):**
   - In C09, praise Meera for asking permission before quoting Vedant's name, adhering to his explicit boundary.
   - In C10, instruct SDR team NOT to place follow-up calls to Aniket despite upstream "follow_up" tag, respecting his explicit boundary (*"No. I said I will contact you if there is anything to discuss"*).
3. **Handling Bank Feed vs Native Card Positioning (M04 - Cedarwave):** Train reps on how to explain SpendNest's core software value (receipt matching, policy compliance, ERP synchronization) when customers bring existing third-party bank credit cards.

---

## 4. Complete Intake & Telephony Record Breakdown
- **Unique Records Intake:** 44 total (30 Calls, 14 Meetings)
- **Validated Transcripts:** 18 records (10 Calls: C01-C10; 8 Meetings: M01-M04, M06, M07, M09, M10)
- **Unusable / Background Telephony:** 20 records (B01-B20: outbound dial attempts without audio/transcript)
- **Recorded Meetings Without Speech:** 3 records (M05, M08, M11: notetaker recorded empty session)
- **Cancelled / Unscheduled Bot Meetings:** 3 records (M12, M14: notetaker cancelled; M13: notetaker not scheduled)
`;

  folders.daily_briefs.file('manager_brief_2026_08_21.md', briefContent);

  // Manifest JSON
  const manifestJsonContent = JSON.stringify({
    manifest_version: '1.0',
    generated_at: new Date().toISOString(),
    date_scope: '2026-08-21 (Asia/Kolkata)',
    total_records: manifestRows.length,
    records: manifestRows
  }, null, 2);
  zip.file('manifest.json', manifestJsonContent);

  // Manifest CSV
  const csvHeaders = ['source_type', 'source_id', 'record_ref', 'applied_revision', 'routes', 'output_paths', 'review_state', 'is_manually_overridden', 'analysis_freshness'];
  const csvLines = [csvHeaders.join(',')];
  manifestRows.forEach(row => {
    const line = csvHeaders.map(h => {
      const val = String(row[h] || '').replace(/"/g, '""');
      return `"${val}"`;
    }).join(',');
    csvLines.push(line);
  });
  zip.file('manifest.csv', csvLines.join('\n'));

  // Generate Blob
  const blob = await zip.generateAsync({ type: 'blob' });
  return blob;
}

export function downloadBlob(blob, filename) {
  const url = URL.createObjectURL(blob);
  const a = document.createElement('a');
  a.href = url;
  a.download = filename;
  document.body.appendChild(a);
  a.click();
  document.body.removeChild(a);
  URL.revokeObjectURL(url);
}
